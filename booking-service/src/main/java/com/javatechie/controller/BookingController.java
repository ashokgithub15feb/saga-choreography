package com.javatechie.controller;

import com.javatechie.request.BookingRequest;
import com.javatechie.response.BookingResponse;
import com.javatechie.service.BookingService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

// Errors are mapped to HTTP responses by exception.GlobalExceptionHandler
@RestController
@RequestMapping("/booking-service")
@Tag(name = "Booking", description = "Start the booking saga")
public class BookingController {

    private final BookingService bookingService;

    public BookingController(BookingService bookingService) {
        this.bookingService = bookingService;
    }

    // Endpoint to handle seat booking requests
    @PostMapping("/bookSeat")
    @Operation(summary = "Book seats",
            description = "Saves the booking (PENDING) and its BookingCreatedEvent (outbox). "
                    + "Retrying with the same Idempotency-Key returns the same booking instead of creating a new one. "
                    + "Amount > 2000 makes the payment step fail and triggers the compensation flow.")
    public ResponseEntity<BookingResponse> bookSeat(
            @Parameter(description = "Unique per booking attempt (e.g. a UUID generated by the client); "
                    + "reuse it only when retrying the same request", required = true)
            @RequestHeader("Idempotency-Key") @NotBlank @Size(max = 100) String idempotencyKey,
            @RequestBody BookingRequest request) {
        return ResponseEntity.ok(bookingService.bookSeats(request, idempotencyKey));
    }

    @GetMapping("/bookings/{reservationId}")
    @Operation(summary = "Booking status",
            description = "Current saga status: PENDING -> SEATS_LOCKED -> CONFIRMED, or FAILED. "
                    + "Poll this after POST /bookSeat, which returns while the saga is still PENDING.")
    public ResponseEntity<BookingResponse> getBooking(@PathVariable String reservationId) {
        return ResponseEntity.ok(bookingService.getBooking(reservationId));
    }
}
